#!/usr/bin/env bash
# Regenerate the manifests that are derived from other files in the repository:
#   manifests/monitoring/dashboard-configmap.yaml   from infra/dashboards/skill-ci.json
#   manifests/harbor-setup/harbor-setup-script.yaml from infra/harbor-setup.sh
#   manifests/seed/skill-ci-models.yaml             from demo/models.yaml
#   manifests/**/kustomization.yaml                 image tags from deploy/versions.env
# Never hand-edit these files.
#   deploy/generate.sh           rewrite them
#   deploy/generate.sh --check   exit 1 if they are out of date (for CI)
set -euo pipefail

deploy_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root_dir="$(cd "${deploy_dir}/.." && pwd)"
# shellcheck source=deploy/versions.env
. "${deploy_dir}/versions.env"

mode="write"
case "${1:-}" in
  "") ;;
  --check) mode="check" ;;
  *)
    echo "usage: $0 [--check]" >&2
    exit 2
    ;;
esac

# configmap OUT NAME NAMESPACE KEY SOURCE [LABEL]: ConfigMap with SOURCE as a block scalar.
configmap() {
  local out="$1" name="$2" namespace="$3" key="$4" source="$5" label="${6-}"
  {
    echo "# Generated by deploy/generate.sh from ${source#"${root_dir}/"}. Do not edit."
    echo "apiVersion: v1"
    echo "kind: ConfigMap"
    echo "metadata:"
    echo "  name: ${name}"
    echo "  namespace: ${namespace}"
    if [[ -n "${label}" ]]; then
      echo "  labels:"
      echo "    ${label}"
    fi
    echo "data:"
    echo "  ${key}: |"
    # Indent every non-empty line; empty lines stay empty (no trailing whitespace).
    sed 's/^\(.\)/    \1/' "${source}"
  } >"${out}"
}

# generate OUTDIR writes every generated file under OUTDIR/manifests.
generate() {
  local out="$1/manifests"
  mkdir -p "${out}/monitoring" "${out}/harbor-setup" "${out}/seed"

  configmap "${out}/monitoring/dashboard-configmap.yaml" skill-ci-dashboard monitoring skill-ci.json \
    "${root_dir}/infra/dashboards/skill-ci.json" 'grafana_dashboard: "1"'
  configmap "${out}/harbor-setup/harbor-setup-script.yaml" harbor-setup-script skill-ci harbor-setup.sh \
    "${root_dir}/infra/harbor-setup.sh"
  # Seed only: the demo edits the model list live, so install.sh creates this ConfigMap and never overwrites it.
  configmap "${out}/seed/skill-ci-models.yaml" skill-ci-models skill-ci models.yaml \
    "${root_dir}/demo/models.yaml"

  cat >"${out}/kustomization.yaml" <<KUSTOMIZATION
# Generated by deploy/generate.sh from deploy/versions.env. Do not edit.
# Core objects: kubectl apply -k deploy/manifests
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - namespaces.yaml
  - toolbox.yaml
images:
  - name: ghcr.io/oras-project/oras
    newTag: ${ORAS_VERSION}
  - name: curlimages/curl
    newTag: "${CURL_VERSION}"
KUSTOMIZATION

  cat >"${out}/monitoring/kustomization.yaml" <<KUSTOMIZATION
# Generated by deploy/generate.sh. Do not edit.
# Needs the kube-prometheus-stack CRDs: kubectl apply -k deploy/manifests/monitoring
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - namespace.yaml
  - servicemonitor.yaml
  - dashboard-configmap.yaml
KUSTOMIZATION

  cat >"${out}/harbor-setup/kustomization.yaml" <<KUSTOMIZATION
# Generated by deploy/generate.sh from deploy/versions.env. Do not edit.
# Delete the old Job first (a Job's pod template is immutable): kubectl apply -k deploy/manifests/harbor-setup
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - harbor-setup-script.yaml
  - job.yaml
images:
  - name: curlimages/curl
    newTag: "${CURL_VERSION}"
KUSTOMIZATION
}

if [[ "${mode}" == write ]]; then
  generate "${deploy_dir}"
  echo "generated manifests under deploy/manifests"
  exit 0
fi

tmp="$(mktemp -d)"
trap 'rm -rf "${tmp}"' EXIT
generate "${tmp}"
status=0
while IFS= read -r -d '' f; do
  rel="${f#"${tmp}/"}"
  if ! diff -u "${deploy_dir}/${rel}" "${f}" >/dev/null 2>&1; then
    echo "out of date: deploy/${rel}" >&2
    status=1
  fi
done < <(find "${tmp}" -type f -print0)
[[ "${status}" == 0 ]] && echo "generated manifests are up to date"
exit "${status}"
